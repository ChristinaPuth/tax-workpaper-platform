"""Render findings.json as the 'errors found' write-up (deliverable 3). Regenerated on every run."""
from __future__ import annotations

ORIGIN = {"extraction": "Pipeline misread", "engine": "Engine rule / missed link", "client": "Client-supplied data",
          "document": "Document issue", "process": "Process / completeness"}


def money(x) -> str:
    return "-" if x in (None, 0) else f"{x:+,.0f}"


def render(findings: list[dict], verified: list[dict], stats: dict) -> str:
    errs = [f for f in findings if f["severity"] == "error"]
    warns = [f for f in findings if f["severity"] == "warning" and not f["check"].startswith(("P5", "P7"))]
    fed = sum(f["federal_effect"] or 0 for f in errs)
    ca = sum(f["california_effect"] or 0 for f in errs)
    out = ["# Errors found in the Okafor-Lindqvist packet", "",
           f"Generated by `run_checks.py` from the packet as delivered. Index: {stats['nodes']:,} nodes, "
           f"{stats['edges']:,} edges, {stats['unresolved_refs']} unresolved references.", "",
           f"**{len(errs)} errors** in the v3 return. Estimated effect if all are corrected: federal {fed:+,.0f}, "
           f"California {ca:+,.0f} (README method: change x v3 tax_effect_rates; payments 1:1; HVAC uses the engine's "
           "own what-if). Effects are first-order: several corrections together cross thresholds, so the real system "
           "recomputes.", "",
           "Positive = more tax / larger balance due.", "",
           "| # | Error | Origin | Federal | California | Caught by |", "|---|---|---|---:|---:|---|"]
    for f in errs:
        out.append(f"| {f['id']} | {f['title']} | {ORIGIN[f['origin']]} | {money(f['federal_effect'])} | "
                   f"{money(f['california_effect'])} | `{f['check']}`{'' if f['generic'] else ' *'} |")
    out += ["", "`*` = rule encoded against this household's records; the rule itself is stated in the check's docstring.", "",
            "## Detail", ""]
    for f in errs:
        out += [f"### {f['id']} - {f['title']}", "", f["detail"], ""]
        if f["corrections"]:
            out.append("Proposed: " + "; ".join(f"`{c['line']}` {c['current']} -> {c['proposed']}" for c in f["corrections"]))
        out.append(f"Attached to: {', '.join(f['nodes'][:6])}  ")
        out.append(f"Evidence: {', '.join(f['evidence'][:6]) or '-'}  ")
        if f.get("related"):
            out.append(f"Related findings: {', '.join(f['related'])}  ")
        if f.get("effect_note"):
            out.append(f"Note: {f['effect_note']}")
        out.append("")
    out += ["## Needs a decision before filing (warnings)", ""]
    for f in warns:
        out.append(f"- **{f['id']}** {f['title']} - {f['detail'][:260]}")
    out += ["", "## Checks that don't trust the engine - and agreed", ""]
    for v in verified:
        out.append(f"- {v['what']}: engine {v['engine']}, independent {v['independent']}")
    variance = [f for f in findings if f["check"].startswith("P5")]
    out += ["", f"## Prior-year variances over the firm threshold: {len(variance)}", "",
            "Each is a reviewer task ('explain'). Variances on a line with an error link to it:", ""]
    out += [f"- {f['title']} - {f['detail'].split('Needs an explanation.')[-1].strip() or 'to explain'}" for f in variance]
    return "\n".join(out) + "\n"
